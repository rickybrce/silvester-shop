</p>
<br/>


<h2>4. Kada se kreira račun za moju narudžbu?</h2>
<p> 
    U trenutku kada prebacite status narudžbe u <b>"Završeno / Fiskalizirano"</b> kreirati će se račun za odabranu narudžbu, fiskalizirati će se te poslati kupcu na email.
</p>
<br/>

<h2>5. Gdje mogu vidjeti popis svih kreiranih računa?</h2>
<p>
    Svi kreirani računi nalaze se unutar Vaše <a href="https://webracun.com" target="_blank">WebRačun</a> aplikacije.
</p>
