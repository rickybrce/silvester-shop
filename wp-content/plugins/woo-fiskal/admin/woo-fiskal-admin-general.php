<h2>1. Što je WooFiskal?</h2>
<p>
    WooFiskal je Wordpress dodatak za WooCommerce pomoću kojeg svi korisnici 
    <a href="https://webracun.com" target="_blank">WebRačun</a> aplikacije mogu kreirati i fiskalizirati račune izravno iz svoje web trgovine.
</p>
<br/>

<h2>2. Kako radi WooFiskal dodatak?</h2>
<p>
    Radi na način da za svaku vašu narudžbu kreira valjani račun i pošalje ga kupcu na email.
</p>
<br/>

<h2>3. Kako aktivirati WooFiskal?</h2>
<p>

    • Potrebno se sa svojim podacima registrirati na webracun.com <br/>
    • Nakon instalacije i aktivacije WooFiskal dodatka na Vašoj Wordpress stranici, 
    potrebno je zatražiti Vaš osobni <b>WebRačun API link</b> koji spaja Vašu web trgovinu i korisnički račun unutar WebRačun aplikacije.<br/><br/>

    WebRačun API link možete zatražiti kontaktom na:
    <br/>
    <a href="mailto:info@webracun.com?subject=WebRačun API link" class="wf-button"><span class="dashicons dashicons-email"></span> info@webracun.com</a>

